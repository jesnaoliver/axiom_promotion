def infer_sectors(topic_text):
    """从雪球话题文本推断板块（申万标签候选，按匹配强度排序）。"""
    if not topic_text:
        return []

    hits = []
    hit_score = {}

    # 板块词（权重高）
    for idx, (kw, sectors) in enumerate(SECTOR_KEYWORDS):
        if kw in topic_text:
            w = 100 - idx
            for s in sectors:
                hit_score.setdefault(s, 0)
                hit_score[s] += w
                if s not in hits:
                    hits.append(s)

    # 公司名（权重低，仅补充板块归属）
    for kw, sectors in COMPANY_NAMES:
        if kw in topic_text:
            for s in sectors:
                if s not in hits:
                    hits.append(s)

    if not hits:
        for kw, sectors in GENERIC_SECTORS:
            if kw in topic_text:
                for s in sectors:
                    if s not in hits:
                        hits.append(s)

    hits.sort(key=lambda s: -hit_score.get(s, 0))
    return hits


def sector_keyword_in(text):
    """找出文本里出现的第一个板块词（用于保住这一段）。"""
    if not text:
        return None
    best = None
    best_idx = 10 ** 9
    for kw, _ in SECTOR_KEYWORDS:
        i = text.find(kw)
        if i >= 0 and i < best_idx:
            best_idx = i
            best = kw
    return best


def concept_keywords(sectors, topic_text):
    """
    给板块生成 Axiom 检索关键词（板块名 + 话题里的概念词）。

    ⚠️ 2026-11-19 补强：**必须包含话题里出现的板块词本身**
    实测"先进封装概念拉升"→ 只给出 ["电子","机械设备"]，
    而情报事实里写的是"光刻技术""封装设备" → 用这组词去筛事实会全筛掉。
    → 现在把话题里命中的板块词（先进封装/光刻/CPO…）也加进关键词。
    """
    kws = []
    for s in sectors[:3]:
        if s not in kws:
            kws.append(s)
    # ⚠️ 话题里的板块词/概念词 —— 用于正文事实筛选
    for kw, _ in SECTOR_KEYWORDS:
        if kw in (topic_text or "") and kw not in kws:
            kws.append(kw)
    for kw, extra in CONCEPT_EXTRA.items():
        if kw in (topic_text or ""):
            for e in extra:
                if e not in kws:
                    kws.append(e)
    return kws[:10]


def sector_display(sectors, topic=""):
    """
    从申万标签生成人能读的板块名。

    ⚠️ 2026-11-19 修正：
    「半导体概念港股走强」原本显示成 "半导体/电子"（申万标签拼接），
    现在优先用**话题里出现的板块词**（"半导体"）→ 更短更自然。
    只有话题里找不到板块词时，才退回申万标签的中文名。
    """
    kw = sector_keyword_in(topic) if topic else None
    if kw:
        return kw
    for s in sectors:
        if s in TAG_DISPLAY:
            return TAG_DISPLAY[s]
    return sectors[0] if sectors else ""


