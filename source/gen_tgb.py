def build_tgb_posts() -> list[dict]:
    """
    生成淘股吧帖子，并过合规闸门。

    分三层：
      1. content/compliance.py        通用红线
      2. content/tgb_compliance.py    淘股吧专属红线
      3. source/sanitize.forbidden_check  项目专属（域名/品牌/代码）

    ⚠️ 主题池必须持续扩容：5 篇全部发完后，
    scheduler 的 fallback 会回退到【已发过】的主题 → 撞规则二.4 重复发帖。
    """
    from content.compliance import check_note
    from source.sanitize import forbidden_check

    posts = [
        post_dedup(),
        post_backtest_hallucination(),
        post_info_tiers(),
        post_agent_howto(),
        post_data_window(),
        post_falsification(),
        post_data_source_diff(),
        post_noise_vs_trend(),
        post_daily_checklist(),
        post_consistency_check(),
    ]

    cleaned = []
    for p in posts:
        issues = []

        r1 = check_note({"title": p["title"], "body": p["body"],
                         "tags": p.get("tags", []), "images": p.get("images", [])},
                        platform="tgb")
        if not r1["passed"]:
            issues += [f"[通用] {v['category']}" for v in r1["violations"]]

        r2 = check_tgb({"title": p["title"], "body": p["body"],
                        "tags": p.get("tags", []), "images": p.get("images", [])})
        if not r2["passed"]:
            issues += [f"[淘股吧] {v['category']}" for v in r2["violations"]]

        issues += [f"[项目] {x}" for x in forbidden_check(p["title"]) + forbidden_check(p["body"])]

        cat = check_category(p.get("category", CATEGORY))
        if not cat["ok"]:
            issues.append(f"[分类] {cat['reason']}")

        if issues:
            print(f"⚠️  跳过 {p['id']}：{issues}")
            continue

        p["_warnings"] = r2["warnings"]
        cleaned.append(p)

    return cleaned


if __name__ == "__main__":
    posts = build_tgb_posts()
    OUT = ROOT / "content" / "for_tgb"
