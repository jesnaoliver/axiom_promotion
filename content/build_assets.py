def main():
    days = int(sys.argv[1]) if len(sys.argv) > 1 else 7
    ASSETS.mkdir(parents=True, exist_ok=True)
    plan = get_daily_plan(days)
    for i, t in enumerate(plan, 1):
        label = "搭系统日志" if t["track"] == "A" else "回测避坑"
        out = ASSETS / f"cover_{t['id']}.jpg"
        make_cover(
            title=t["cover"],
            label=label,
            out_path=out,
            palette_idx=(i - 1) % 5,
            footer="记录 · 不构成投资建议",
            bullets=BULLETS.get(t["id"]),
            badge=f"D{i:02d}",
        )
        print(f"Day{i} [{t['id']}] {out.name}  <- {t['cover']}")
    print(f"\n共生成 {len(plan)} 张封面 -> {ASSETS}")


if __name__ == "__main__":
    main()
