    (r"\b[a-z0-9-]+\.(cn|com|net|org|cc|xyz|top|vip|io)\b", "域名"),
    (r"(微信|weixin|wx|威信|VX|扣扣|QQ|weibo|微博)\s*[:：]?\s*[a-zA-Z0-9_-]{4,}", "联系方式"),
