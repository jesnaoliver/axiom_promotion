def check_tgb(note: dict) -> dict:
    """
    淘股吧合规检查。

    note 需含：title / body / tags（可选）/ images（可选）
    返回与 compliance.check_note 同构的 dict。
    """
    title = note.get("title", "") or ""
    body = note.get("body", "") or ""
    tags = " ".join(note.get("tags", []) or [])
    text = f"{title}\n{body}\n{tags}"

    violations = []
    warnings = []

    def hit(category, matched, where="body"):
        violations.append({
            "category": category,
            "hits": [matched],
            "where": where,
            "platform": "tgb",
        })

    # ---- 1. 个股代码（任何形式）----
    m = STOCK_CODE.search(text)
    if m:
        hit("出现个股代码", m.group(0))

    # ---- 2. 买卖方向 ----
    for pat in TRADE_DIRECTION:
        m = re.search(pat, text)
        if m:
            hit("买卖方向/投资建议表述", m.group(0))

    # ---- 3. 收益与业绩数字 ----
    for pat in PERFORMANCE:
        m = re.search(pat, text)
        if m:
            hit("展示收益/胜率等业绩", m.group(0))

    # ---- 4. 站外引流 ----
    for pat, desc in TRAFFIC:
        m = re.search(pat, text, re.IGNORECASE)
        if m:
            hit(desc, m.group(0))

    # ---- 5. 暗语/变体 ----
    for pat, desc in VAGUE:
        m = re.search(pat, text)
        if m:
            hit(desc, m.group(0)[:30])

    # ---- 6. 二次分发 ----
    for pat, desc in SECONDARY:
        m = re.search(pat, text)
        if m:
            hit(desc, m.group(0))

    # ---- 7. 广告自推 ----
    for pat, desc in PROMOTION:
        m = re.search(pat, text)
        if m:
            hit(desc, m.group(0))

    # ---- 8. 荐股软件功能宣传 ----
    for pat, desc in RECOMMEND_SOFTWARE:
        m = re.search(pat, text)
        if m:
            hit(desc, m.group(0))

    # ---- 9. 结构检查 ----
    title_len = len(title)
    if title_len > 50:
        warnings.append({"category": "标题偏长", "detail": f"{title_len}字",
                         "platform": "tgb"})
    if title_len < 10:
        warnings.append({"category": "标题过短", "detail": f"{title_len}字，论坛标题宜15字以上",
                         "platform": "tgb"})
    body_len = len(body)
    if body_len < 100:
        violations.append({
            "category": "正文过短",
            "hits": [f"{body_len}字，淘股吧主贴要求≥100字"],
            "where": "body",
            "platform": "tgb",
        })
    if body_len > 8000:
        warnings.append({"category": "正文偏长", "detail": f"{body_len}字，论坛建议1500-3000字",
                         "platform": "tgb"})

    # ---- 10. 必备声明 ----
    if "不构成" not in body and "不作为" not in body and "风险自担" not in body:
        violations.append({
            "category": "缺少投资风险提示",
            "hits": ["需包含「不构成投资建议」「风险自担」等表述"],
            "where": "body",
            "platform": "tgb",
        })

    # ---- 11. 工具名出现警告 ----
    # 规则一.10：产品自推算广告。提及开源项目名相对安全，但需提示
    for kw in ["AXIOM", "vibe-trading", "efficientinvest", "WorkBuddy"]:
        if kw.lower() in text.lower():
            warnings.append({
                "category": "含产品名",
                "detail": f"出现「{kw}」。淘股吧规则一.10 将产品推广视同广告，"
                          f"且先审后发+案底制下风险不可逆。个人号建议完全不提产品名",
                "platform": "tgb",
            })
            break

    # ---- 12. 分发节奏提醒 ----
    warnings.append({
        "category": "发帖节奏",
        "detail": "规则二.4禁止大量重复发帖；官方明示创作中心1级前每天发言次数受限，"
                  "且违规会回溯历史发言。建议先发1篇观察24-72小时审核与反馈",
        "platform": "tgb",
    })

    return {
        "platform": "tgb",
        "passed": len(violations) == 0,
        "violations": violations,
        "warnings": warnings,
        "checked_fields": {
            "title_len": title_len,
            "body_len": body_len,
            "tag_count": len(note.get("tags", []) or []),
            "image_count": len(note.get("images", []) or []),
        },
    }


def check_category(category: str) -> dict:
    """
    发帖分类检查。

    ⚠️ 关键：淘股吧的"个股研究"分类**强制要求**通过选择器输入 1-5 支个股，
    选了它就等于把账号与个股强绑定 → 构成金永荣案的事实画像。
    → 个人号做方法论内容，只能选「方法论」或「其他」。
    """
    allowed = {"方法论", "其他", "复盘"}
    banned = {"个股研究", "实盘", "研股"}
    if category in banned:
        return {
            "ok": False,
            "reason": f"分类「{category}」不可用："
                      f"个股研究强制输入1-5支个股（等同公开荐股），"
                      f"实盘/研股直接涉及个股与收益结算。"
                      f"请改用「方法论」或「其他」",
        }
    if category not in allowed:
        return {"ok": True, "reason": f"分类「{category}」不在推荐列表，请人工确认"}
    return {"ok": True, "reason": f"分类「{category}」安全"}


