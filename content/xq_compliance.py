def _sentence_of(text: str, token: str) -> str:
    """取 token 所在的那一句（用于判断上下文）。"""
    if not token:
        return ""
    i = text.find(token)
    if i < 0:
        return ""
    left = text[:i]
    right = text[i + len(token):]
    # 向前找最近的句读
    for ch in "。！？\n；;":
        j = left.rfind(ch)
        if j >= 0:
            left = left[j + 1:]
            break
    # 向后找最近的句读
    for ch in "。！？\n；;":
        j = right.find(ch)
        if j >= 0:
            right = right[:j]
            break
    return left + token + right


def check_xq(note: dict) -> dict:
    """
    雪球合规检查。

    note 需含：title / body / tags / images / ai_marked
    ai_marked: 是否勾选了 AI 生成内容标识（雪球强制要求）
    """
    title = note.get("title", "") or ""
    body = note.get("body", "") or ""
    tags = " ".join(note.get("tags", []) or [])
    text = f"{title}\n{body}\n{tags}"

    violations = []
    warnings = []

    def hit(category, matched, where="body"):
        violations.append({
            "category": category,
            "hits": [matched],
            "where": where,
            "platform": "xueqiu",
        })

    # 1. 个股代码
    m = STOCK_CODE.search(text)
    if m:
        hit("出现个股代码", m.group(0))

    # 2. 个股指代
    for pat in STOCK_ALIAS:
        m = re.search(pat, text)
        if m:
            hit("疑似个股指代", m.group(0))

    # 2b. 泛指型（某只票/某只股票）—— 只在**带方向判断**时才算违规
    #     "某只票后来被划到某个行业"（讲方法论）→ 允许
    #     "今天可以买某只票"（给方向）→ 拦截
    for m in GENERIC_STOCK.finditer(text):
        sent = _sentence_of(text, m.group(0))
        if re.search(r"(买|卖|看好|看多|看空|推荐|持有|加仓|减仓|入场|出场|"
                     r"关注|布局|目标|上车)", sent):
            hit("泛指个股+方向判断", m.group(0))
            break

    # 3. 买卖方向
    for pat in TRADE_DIRECTION:
        m = re.search(pat, text)
        if m:
            hit("买卖方向/投资建议表述", m.group(0))

    # 4. 业绩数字（必须与展示动词共现才算违规）
    for pat, desc in PERFORMANCE_PAIRS:
        m = re.search(pat, text)
        if not m:
            continue
        # 看该数字所在句子是否含展示动词
        sentence = _sentence_of(text, m.group(0))
        if re.search(SHOW_VERB, sentence):
            hit(desc, m.group(0))
        else:
            warnings.append({
                "category": "提到业绩类概念",
                "detail": f"「{m.group(0)}」出现在方法论语境（非展示）。"
                          f"若上下文变成晒盘/收益展示则违规",
                "platform": "xueqiu",
            })

    # 4b. 截图类（无论上下文，晒图都违规）
    for pat in (r"(收益|盈利|利润|持仓|交割单|对账单|账户)截图",
                r"(晒|展示|附上|上图|贴出).{0,6}(收益|盈利|利润|战绩|持仓|交割单|账户)"):
        m = re.search(pat, text)
        if m:
            hit("晒盘/晒图", m.group(0))
            break

    # 5. 晒盘
    for pat in SHOW_OFF:
        m = re.search(pat, text)
        if m:
            hit("晒盘/股神人设", m.group(0))

    # 6. 站外引流
    for pat, desc in TRAFFIC:
        m = re.search(pat, text, re.IGNORECASE)
        if m:
            hit(desc, m.group(0))

    # 7. 二次分发
    for pat, desc in SECONDARY:
        m = re.search(pat, text)
        if m:
            hit(desc, m.group(0))

    # 8. 产品自推
    for pat, desc in PROMOTION:
        m = re.search(pat, text)
        if m:
            hit(desc, m.group(0))

    # 9. AI 荐股功能
    for pat, desc in RECOMMEND_SOFTWARE:
        m = re.search(pat, text)
        if m:
            hit(desc, m.group(0))

    # 10. AI 标识（雪球强制）
    ai_marked = note.get("ai_marked")
    if ai_marked is None:
        # 未声明 → 从正文推断
        ai_marked = bool(AI_MARK.search(text))
    if not ai_marked:
        violations.append({
            "category": "缺少AI生成内容标识",
            "hits": ["雪球社区规则第十二章第4款：涉AI生成内容必须主动标识"],
            "where": "meta",
            "platform": "xueqiu",
        })

    # 11. 标题与结构
    title_len = len(title)
    if title_len > 30:
        warnings.append({"category": "标题偏长", "detail": f"{title_len}字",
                         "platform": "xueqiu"})
    if title_len < 8:
        warnings.append({"category": "标题过短", "detail": f"{title_len}字",
                         "platform": "xueqiu"})
    body_len = len(body)
    if body_len < 300:
        violations.append({
            "category": "正文过短",
            "hits": [f"{body_len}字，雪球长文建议≥500字"],
            "where": "body",
            "platform": "xueqiu",
        })

    # 12. 风险提示
    if not re.search(r"不构成(任何)?投资建议|不作为(任何)?投资建议|"
                     r"仅供研究方法交流|不构成任何投资建议", body):
        warnings.append({
            "category": "缺少投资风险提示",
            "detail": "必要但不充分 —— 浙江证监局45号已明确免责声明无效，"
                      "必须同时有能力边界的事实陈述",
            "platform": "xueqiu",
        })

    # 13. 能力边界陈述（比免责条款更重要的合规资产）
    boundary_markers = ["不做选股", "不预测", "不给买卖点", "不推荐",
                         "不输出具体", "只做检查", "只是工具", "不替代判断",
                         "不构成决策", "我不下", "没推荐过", "只负责检查"]
    if not any(k in body for k in boundary_markers):
        warnings.append({
            "category": "缺少能力边界声明",
            "detail": "建议加入事实陈述式边界（如「它不做选股、不给买卖点」）。"
                      "浙江证监局45号：免责声明无效，但能力边界是有效资产",
            "platform": "xueqiu",
        })

    # 14. 产品名 —— **硬拦截**（原实现只报 warning，等于放行，2026-11-11 修正）
    # ⚠️ 实测踩坑：产品名是「绝对不得出现」项，若只警告不拦截，
    #   含「AXIOM」的稿子能同时通过三层闸门 → 会被发出去。
    #   雪球第八章禁止广告营销；且《金融产品网络营销管理办法》第二条第二款下，
    #   个人号推自建收费金融工具本身即禁止 → 没有任何「轻微」的余地。
    for kw in ["AXIOM", "vibe-trading", "efficientinvest", "WorkBuddy", "小雪",
               "AX IOM", "_axiom_", "axiom"]:
        if kw.lower() in text.lower():
            hit("含产品名（绝对禁止出现）", kw)
            break

    return {
        "platform": "xueqiu",
        "passed": len(violations) == 0,
        "violations": violations,
        "warnings": warnings,
        "checked_fields": {
            "title_len": title_len,
            "body_len": body_len,
            "tag_count": len(note.get("tags", []) or []),
            "image_count": len(note.get("images", []) or []),
            "ai_marked": bool(ai_marked),
        },
    }


