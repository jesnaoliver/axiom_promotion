def get_daily_plan(days: int = 7) -> list[dict]:
    """
    生成日更排期。
      - 主线 A 与支线 B 交替，避免连续同赛道导致同质化降权
      - 目标比例：每周 5 条 A + 2 条 B
    """
    a = [t for t in TOPIC_BANK if t["track"] == "A"]
    b = [t for t in TOPIC_BANK if t["track"] == "B"]
    # 7天排期：A B A B A A B  →  A=4, B=3
    order = ["A", "B", "A", "B", "A", "A", "B"]
    plan, ai, bi = [], 0, 0
    for i in range(days):
        track = order[i % len(order)] if days <= 7 else ("A" if i % 7 in (0, 2, 4, 5) else "B")
        if track == "A" and ai < len(a):
            plan.append(a[ai]); ai += 1
        elif bi < len(b):
            plan.append(b[bi]); bi += 1
        elif ai < len(a):
            plan.append(a[ai]); ai += 1
    return plan


